"""
Regenerate requirements.lock from the current Python environment.

Usage
-----
    .venv/Scripts/python.exe scripts/lock_requirements.py

Sale del ``.venv`` del repo, que es el entorno canónico (tarea 401); desde otro intérprete se
niega, salvo con ``--forzar``.

Behaviour
---------
1. Resolve the project root (one level up from this file).
2. Run ``pip freeze`` in the active interpreter's environment.
3. Write the output to ``requirements.lock``, prepending a header comment
   with timestamp and Python version so it's clear when/how it was made.

The script is intentionally minimal — no third-party deps. It only uses the
stdlib so it works in any environment where requirements.txt was installed.
"""

from __future__ import annotations

import datetime as _dt
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK_PATH = ROOT / "requirements.lock"
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def main(argv: list[str] | None = None) -> int:
    from config.entorno import es_el_venv

    # Tarea 401: el lock del 2026-10-16 salió del .venv mientras la app corría en la Anaconda, y
    # su encabezado no decía de qué entorno era. Sale del .venv, o se fuerza a sabiendas.
    forzar = "--forzar" in (sys.argv[1:] if argv is None else argv)
    if not es_el_venv(sys.prefix) and not forzar:
        print(
            f"El lock sale del .venv del repo (tarea 401), y éste es {sys.prefix}. "
            "Corré .venv/Scripts/python.exe scripts/lock_requirements.py, o pasá --forzar.",
            file=sys.stderr,
        )
        return 2
    try:
        result = subprocess.run(
            [sys.executable, "-m", "pip", "freeze", "--all"],
            capture_output=True,
            check=True,
            text=True,
        )
    except subprocess.CalledProcessError as exc:
        print(f"pip freeze failed: {exc.stderr}", file=sys.stderr)
        return 1

    header = (
        "# Auto-generated by scripts/lock_requirements.py — do not edit by hand.\n"
        f"# Generated: {_dt.datetime.now().isoformat(timespec='seconds')}\n"
        f"# Python:    {sys.version.splitlines()[0]}\n"
        f"# Entorno:   {sys.prefix}\n"
        "#\n"
        "# Install with:  pip install -r requirements.lock\n"
        "# Regenerate:    .venv/Scripts/python.exe scripts/lock_requirements.py\n"
        "\n"
    )
    # `newline="\n"` explícito (tarea 165): el lock está versionado y el repo es LF; sin
    # esto, regenerarlo en Windows lo flipea a CRLF entero (ya pasó — el archivo en disco
    # quedó CRLF contra un blob LF).
    LOCK_PATH.write_text(header + result.stdout, encoding="utf-8", newline="\n")
    n_lines = len([l for l in result.stdout.splitlines() if l and not l.startswith("#")])
    print(f"Wrote {n_lines} pinned packages to {LOCK_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
